# 4. What is bias?
# Answer: Bias is the error caused by overly simple assumptions in a model.

# 5. What is variance?
# Answer: Variance is the sensitivity of a model to changes in the
# training data.

# 6. Which tree has higher bias?
# Answer: A simple Decision Tree.

# 7. Which tree has higher variance?
# Answer: A complex Decision Tree.

# 8. Which tree is more likely to overfit?
# Answer: A complex Decision Tree.

# 9. Which tree is easier to interpret?
# Answer: A simple Decision Tree.

