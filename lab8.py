# Question 8: Is it better to prefer simple decision trees over complex trees?
# Aim: Demonstrate impact of tree complexity on underfitting/overfitting and bias-variance.
# Answer
# Yes, it is generally better to prefer simple Decision Trees instead
# of long and complex Decision Trees.

# A simple Decision Tree:
# - Is easy to understand.
# - Trains faster.
# - Reduces overfitting.
# - Generalizes better to new data.

# A complex Decision Tree:
# - Has many branches and nodes.
# - May memorize the training data (overfitting).
# - Performs well on training data but may perform poorly on unseen data.

# Relationship between Complexity and Bias
# - Simple Decision Tree → Higher Bias, Lower Variance
# - Complex Decision Tree → Lower Bias, Higher Variance

# A balanced or pruned Decision Tree provides the best trade-off
# between bias and variance.

# Conclusion
# Simple Decision Trees are generally preferred because they are easier
# to understand, reduce overfitting, and usually perform better on
# unseen data.

